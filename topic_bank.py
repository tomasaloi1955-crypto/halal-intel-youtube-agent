# ── хранилище ────────────────────────────────────────────────────────────────

def _load(name):
    path = dpath(f"bank_{name}.json")
    if os.path.exists(path):
        try:
            with open(path, encoding="utf-8") as f:
                return json.load(f)
        except Exception as e:
            print(f"[BANK] {name}: файл повреждён ({e}) — начинаю заново")
    return {"cursor": 0, "queue": [], "used": []}


def _save(name, data):
    try:
        with open(dpath(f"bank_{name}.json"), "w", encoding="utf-8") as f:
            json.dump(data, f, ensure_ascii=False, indent=2)
    except Exception as e:
        print(f"[BANK] {name}: не сохранил состояние: {e}")


def _ask_gemini(prompt):
    try:
        text = _model.generate_content(prompt).text.strip()
        if text.startswith("```"):
            text = text.split("```")[1]
            if text.startswith("json"):
                text = text[4:]
        return json.loads(text.strip()).get("topics", [])
    except Exception as e:
        print(f"[BANK] Поиск новых тем не удался: {e}")
        return []


