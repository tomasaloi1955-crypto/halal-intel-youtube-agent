_BANKS = {
    "prompts": (BASE_PROMPTS, "task", _research_prompts),
    "tricks": (BASE_TRICKS, "trick", _research_tricks),
}


def next_topic(name):
    """Следующая тема рубрики. Курсор двигается на каждом выпуске, а не раз в неделю."""
    base, key, research = _BANKS[name]
    state = _load(name)
    cursor = int(state.get("cursor", 0))

    if cursor < len(base):
        topic = base[cursor]
        state["cursor"] = cursor + 1
    elif state.get("queue"):
        topic = state["queue"].pop(0)
    else:
        print(f"[BANK] {name}: запас кончился, ищу новые темы...")
        found = research(state.get("used", []))
        if not found:
            # Ничего не нашли — лучше повторить старую тему, чем сорвать выпуск.
            topic = base[cursor % len(base)]
            state["cursor"] = cursor + 1
            print(f"[BANK] {name}: новых тем нет, беру базовую заново")
            state.setdefault("used", []).append(topic.get(key, ""))
            _save(name, state)
            return topic
        topic = found[0]
        state["queue"] = found[1:]

    state.setdefault("used", []).append(topic.get(key, ""))
    if len(state.get("queue", [])) < REFILL_AT and cursor >= len(base) - REFILL_AT:
        try:
            state["queue"] = (state.get("queue") or []) + research(state["used"])
        except Exception as e:
            print(f"[BANK] {name}: пополнение запаса пропущено: {e}")
    _save(name, state)
    return topic


def next_prompt_topic():
    return next_topic("prompts")


def next_trick_topic():
    return next_topic("tricks")


