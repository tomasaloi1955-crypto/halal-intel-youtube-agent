# ai_shorts.py — сценарии Shorts нового формата: короткие, с содержанием В КАДРЕ.
#
# Отличие от ai_processor.py: там нейросеть писала сплошной текст на 140-180 слов
# (55-75 секунд), а картинку подбирал сток. Досмотр до конца — главный сигнал для
# ленты Shorts — на такой длине не вытянуть, а сток ничего зрителю не даёт.
#
# Здесь нейросеть заполняет СТРУКТУРУ конкретной рубрики (крючок, боль, сам промпт,
# три шага, результат), а Python собирает из неё и сцены для кадров, и текст озвучки.
# Просить у модели готовый массив сцен было бы хрупко — она путает поля и ломает
# монтаж; список полей с фиксированными именами она заполняет надёжно.
import json

from ai_processor import (SYSTEM_BASE, NICHE_HASHTAGS, NICHE_TAGS_JSON,
                          BRAND_HANDLE, CHANNEL_LINK, _call_gemini, _hook_block)

# Замер на живой озвучке: ElevenLabs читает по-русски ~2,2 слова в секунду, то есть
# 60 слов ≈ 27 секунд. Раньше в сценарий закладывалось 140-180 слов (55-75 секунд) —
# на такой длине Shorts не досматривают, а досмотр и есть главный сигнал для ленты.
LENGTH_RULE = """ДЛИНА: весь ролик — 25-30 секунд, это 55-68 слов ВСЕГО на все реплики
вместе. Каждая реплика короткая, разговорная, на «ты». Не пересказывай — говори только
то, чего нет на экране: экран показывает суть, голос её объясняет."""

SCREEN_RULE = """ТЕКСТ НА ЭКРАН пиши отдельно от реплики и КОРОТКО (не больше 8 слов):
это надпись, а не предложение. Голос и надпись не должны дословно совпадать."""


def _shorts_script(scenes):
    """Текст озвучки — это просто реплики сцен подряд. Отдельного скрипта нет:
    иначе голос и картинка разъезжаются."""
    return " ".join((s.get("say") or "").strip() for s in scenes if s.get("say"))


def _pack(scenes, c, rubric):
    """Приводит ответ нейросети к контракту, который ждут main.py и соцсети."""
    script = _shorts_script(scenes)
    return {
        "rubric": rubric,
        "scenes": scenes,
        "shorts_script": script,
        "title_shorts": c.get("title_shorts", "")[:100],
        "cover_text": c.get("cover_text", ""),
        "cover_subtitle": c.get("cover_subtitle", ""),
        "tags": c.get("tags") or [],
        "description": c.get("description", ""),
    }


# ── рубрика «Промпт дня» ─────────────────────────────────────────────────────
# Прямой аналог «арабского слова дня»: зритель уносит с собой одну готовую вещь.
# Кадр с промптом — то, ради чего ставят на паузу и сохраняют ролик, а сохранение
# для ленты Shorts весит больше, чем просмотр.

PROMPT_CARD_RUBRIC = "Промпт дня"


def process_prompt_card(topic):
    task = topic.get("task", "")
    who = topic.get("who", "предприниматель")
    prompt = f"""{SYSTEM_BASE}
{_hook_block()}
Рубрика «Промпт дня»: один готовый промпт, который зритель копирует и применяет
сегодня же. Задача выпуска: {task}
Для кого: {who}

{LENGTH_RULE}
{SCREEN_RULE}

ГЛАВНОЕ ТРЕБОВАНИЕ: поле prompt_text — это САМ ПРОМПТ, который можно скопировать
дословно и вставить в ChatGPT. Он должен быть рабочим и конкретным: роль, задача,
ограничения, и плейсхолдер в квадратных скобках для данных зрителя. 30-45 слов.
Не описание промпта, не «попроси нейросеть» — именно текст промпта.

Верни ТОЛЬКО валидный JSON:
{{
  "hook_say": "первая фраза, 10-14 слов — конкретика, которая останавливает пролистывание",
  "hook_text": "та же мысль на экран, до 7 слов",
  "pain_say": "8-12 слов: на что предприниматель тратит время сейчас",
  "pain_text": "на экран, до 6 слов",
  "prompt_say": "18-26 слов: короткая подводка И зачитанное вслух начало самого промпта — пока ты его читаешь, зритель успевает переписать карточку с экрана",
  "prompt_text": "САМ ПРОМПТ ДОСЛОВНО, 30-45 слов, с плейсхолдером в [квадратных скобках]",
  "steps_say": "8-12 слов: как применить",
  "steps": ["шаг 1, до 5 слов", "шаг 2, до 5 слов", "шаг 3, до 5 слов"],
  "result_say": "8-12 слов: что зритель получит, с конкретикой",
  "result_number": "короткая величина результата, напр. '−6 часов' или 'за 40 секунд'",
  "result_text": "расшифровка числа, до 8 слов",
  "cta_say": "финальная реплика: короткий вывод по совести + ОДИН конкретный вопрос зрителю",
  "cta_text": "на экран, до 6 слов",
  "title_shorts": "заголовок до 60 символов, без стоп-слов и капслока",
  "cover_text": "3-5 слов для обложки",
  "cover_subtitle": "подзаголовок 4-6 слов",
  "tags": {NICHE_TAGS_JSON},
  "description": "описание 120-160 слов. ПЕРВАЯ строка — ❓ и тот же вопрос, что в cta_say. Затем ПОЛНЫЙ текст промпта отдельным блоком (его ищут в описании) и разбор. В конце: 'Полный разбор — в Telegram → {CHANNEL_LINK}. Внедрение ИИ под ключ — {BRAND_HANDLE}.' и хэштеги: {NICHE_HASHTAGS}"
}}"""
    c = _call_gemini(prompt)
    if not isinstance(c, dict) or not c.get("prompt_text"):
        return None

    steps = (c.get("steps") or [])[:3]
    scenes = [
        {"kind": "hook", "say": c.get("hook_say", ""), "text": c.get("hook_text", "")},
        {"kind": "text", "say": c.get("pain_say", ""), "text": c.get("pain_text", ""),
         "label": "Сейчас это делается так"},
        {"kind": "prompt", "say": c.get("prompt_say", ""), "text": c["prompt_text"]},
        {"kind": "steps", "say": c.get("steps_say", ""), "steps": steps, "active": 1},
        {"kind": "number", "say": c.get("result_say", ""),
         "number": c.get("result_number", ""), "text": c.get("result_text", ""),
         "label": "Что это даёт"},
        {"kind": "cta", "say": c.get("cta_say", ""), "text": c.get("cta_text", "")},
    ]
    return _pack(scenes, c, PROMPT_CARD_RUBRIC)


# ── рубрика «ИИ за 20 секунд» ────────────────────────────────────────────────
# Одна конкретная фишка инструмента, разложенная на три шага. Шаги подсвечиваются
# по очереди ровно в такт голосу — это и создаёт ощущение движения без стока.

TRICK_RUBRIC = "ИИ за 20 секунд"


def process_ai_trick(topic):
    tool = topic.get("tool_name", "")
    trick = topic.get("trick", "")
    prompt = f"""{SYSTEM_BASE}
{_hook_block()}
Рубрика «ИИ за 20 секунд»: одна малоизвестная фишка инструмента, которую зритель
повторит сразу после ролика.
Инструмент: {tool}
Фишка: {trick}

{LENGTH_RULE}
{SCREEN_RULE}

Шаги должны быть ДЕЙСТВИЯМИ, которые реально выполняются в интерфейсе («открой…»,
«нажми…», «вставь…»), а не общими словами. Если фишка платная или есть подвох —
честно скажи об этом в cta_say, не продавай зрителю иллюзию.

Верни ТОЛЬКО валидный JSON:
{{
  "hook_say": "первая фраза, 10-14 слов — конкретный факт про инструмент, не вопрос",
  "hook_text": "на экран, до 7 слов",
  "what_say": "8-12 слов: что именно умеет эта фишка",
  "what_text": "на экран, до 6 слов",
  "steps": ["шаг 1, до 5 слов", "шаг 2, до 5 слов", "шаг 3, до 5 слов"],
  "step_says": ["реплика к шагу 1, 6-10 слов", "реплика к шагу 2, 6-10 слов", "реплика к шагу 3, 6-10 слов"],
  "result_say": "8-12 слов: что получится в итоге",
  "result_number": "короткая величина, напр. 'за 15 секунд'",
  "result_text": "расшифровка, до 8 слов",
  "cta_say": "вывод по совести + ОДИН конкретный вопрос зрителю",
  "cta_text": "на экран, до 6 слов",
  "title_shorts": "заголовок до 60 символов",
  "cover_text": "3-5 слов",
  "cover_subtitle": "4-6 слов",
  "tags": {NICHE_TAGS_JSON},
  "description": "описание 120-160 слов. ПЕРВАЯ строка — ❓ и тот же вопрос. Затем шаги списком. В конце: 'Полный разбор — в Telegram → {CHANNEL_LINK}. Внедрение ИИ под ключ — {BRAND_HANDLE}.' и хэштеги: {NICHE_HASHTAGS}"
}}"""
    c = _call_gemini(prompt)
    if not isinstance(c, dict) or not c.get("steps"):
        return None

    steps = (c.get("steps") or [])[:3]
    says = (c.get("step_says") or [])[:3]
    scenes = [
        {"kind": "hook", "say": c.get("hook_say", ""), "text": c.get("hook_text", "")},
        {"kind": "text", "say": c.get("what_say", ""), "text": c.get("what_text", ""),
         "label": tool[:28]},
    ]
    # Один и тот же список шагов, но подсвечивается очередной — глаз ведут по кадру.
    for i in range(len(steps)):
        scenes.append({"kind": "steps", "say": says[i] if i < len(says) else "",
                       "steps": steps, "active": i, "label": "По шагам"})
    scenes += [
        {"kind": "number", "say": c.get("result_say", ""),
         "number": c.get("result_number", ""), "text": c.get("result_text", ""),
         "label": "Результат"},
        {"kind": "cta", "say": c.get("cta_say", ""), "text": c.get("cta_text", "")},
    ]
    return _pack(scenes, c, TRICK_RUBRIC)


