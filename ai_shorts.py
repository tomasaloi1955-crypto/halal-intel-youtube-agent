# ── рубрика «Халяль или харам?» ──────────────────────────────────────────────
# Единственный формат, который не повторит ни один из тысячи одинаковых AI-каналов.
# Финальный кадр — выбор А/Б: ответить одной буквой легко, поэтому комментарии
# пишут те, кто обычно молчит.

VERDICT_RUBRIC = "Халяль или харам?"


def process_verdict_short(topic):
    practice = topic.get("practice", "")
    prompt = f"""{SYSTEM_BASE}
{_hook_block()}
Фирменная рубрика «Халяль или харам?»: честный разбор спорного приёма применения ИИ.
Приём: {practice}

{LENGTH_RULE}
{SCREEN_RULE}

Вердикт не должен быть трусливым, но и не выдавай себя за муфтия: формулировка —
«халяль, если…» / «харам, если…», с опорой на понятные критерии (честность к
клиенту, отсутствие обмана и скрытого вреда). Поле verdict — РОВНО одно из:
"Халяль", "Харам", "Зависит".

В options дай два РАЗНЫХ живых мнения, за каждым из которых стоит своя правда —
иначе выбирать нечего и комментариев не будет.

Верни ТОЛЬКО валидный JSON:
{{
  "hook_say": "первая фраза, 10-14 слов — конкретная сцена, где этот приём применяют",
  "hook_text": "на экран, до 7 слов",
  "how_say": "10-14 слов: как это работает на практике",
  "how_text": "на экран, до 6 слов",
  "verdict": "Халяль | Харам | Зависит",
  "verdict_say": "10-14 слов: вердикт и главный критерий, по которому он вынесен",
  "verdict_text": "условие вердикта одной строкой, до 10 слов",
  "choice_say": "8-12 слов: предложи выбрать А или Б в комментариях",
  "options": ["мнение А, до 8 слов", "мнение Б, до 8 слов"],
  "cta_say": "короткая финальная реплика",
  "cta_text": "на экран, до 6 слов",
  "title_shorts": "заголовок до 60 символов, можно с вопросом",
  "cover_text": "3-5 слов",
  "cover_subtitle": "4-6 слов",
  "tags": {NICHE_TAGS_JSON},
  "description": "описание 120-160 слов. ПЕРВАЯ строка — ❓ и вопрос «А или Б?» с расшифровкой вариантов. В конце: 'Полный разбор — в Telegram → {CHANNEL_LINK}. Внедрение ИИ под ключ — {BRAND_HANDLE}.' и хэштеги: {NICHE_HASHTAGS}"
}}"""
    c = _call_gemini(prompt)
    if not isinstance(c, dict) or not c.get("verdict"):
        return None

    scenes = [
        {"kind": "hook", "say": c.get("hook_say", ""), "text": c.get("hook_text", "")},
        {"kind": "text", "say": c.get("how_say", ""), "text": c.get("how_text", ""),
         "label": "Как это работает"},
        {"kind": "verdict", "say": c.get("verdict_say", ""),
         "verdict": c.get("verdict", ""), "text": c.get("verdict_text", "")},
        {"kind": "choice", "say": c.get("choice_say", ""),
         "options": c.get("options") or []},
        {"kind": "cta", "say": c.get("cta_say", ""), "text": c.get("cta_text", "")},
    ]
    return _pack(scenes, c, VERDICT_RUBRIC)
