def pick_most_interesting(articles):
    """
    Из пула свежих новостей выбирает ОДНУ — самую интересную и кликабельную
    для аудитории канала. Возвращает индекс в списке.
    """
    if not articles:
        return None
    if len(articles) == 1:
        return 0

    listing = "\n".join(
        f"{i}. {a['title']} — {a.get('summary','')[:200]}"
        for i, a in enumerate(articles)
    )
    prompt = f"""{SYSTEM_BASE}

Вот список свежих AI-новостей. Выбери РОВНО ОДНУ — самую интересную и кликабельную
для нашей аудитории (предприниматели и мусульмане СНГ, 25-45 лет).
Критерии: вау-эффект, практическая польза для бизнеса, обсуждаемость, эмоция.
Избегай узкотехнических, корпоративно-скучных и проходных новостей.

Верни ТОЛЬКО валидный JSON: {{"index": <номер из списка>, "reason": "<коротко почему именно она>"}}

Новости:
{listing}"""
    res = _call_gemini(prompt)
    if isinstance(res, dict) and isinstance(res.get("index"), int) and 0 <= res["index"] < len(articles):
        print(f"[AI] Выбрана новость #{res['index']}: {res.get('reason', '')}")
        return res["index"]
    print("[AI] Не удалось выбрать — беру первую")
    return 0


